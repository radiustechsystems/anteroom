// TestActivitySection pins the optional-section contract: absent means nil
// (no per-visitor state anywhere), present-but-empty means the documented
// defaults, and explicit values stick.
func TestActivitySection(t *testing.T) {
	cfg, err := Load(write(t, minimal))
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Activity != nil {
		t.Fatalf("activity should default off, got %+v", cfg.Activity)
	}

	cfg, err = Load(write(t, minimal+"[activity]\n"))
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Activity == nil || cfg.Activity.TTL.D() != 10*time.Minute || cfg.Activity.MaxIPs != 8192 {
		t.Fatalf("empty section defaults wrong: %+v", cfg.Activity)
	}

	cfg, err = Load(write(t, minimal+"[activity]\nttl = \"30m\"\nmax_ips = 100\n"))
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Activity.TTL.D() != 30*time.Minute || cfg.Activity.MaxIPs != 100 {
		t.Fatalf("explicit values not honored: %+v", cfg.Activity)
	}
}

