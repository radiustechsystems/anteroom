// replaceKey rewrites `key = ...` in a TOML body regardless of column
// alignment, so tests do not break when the example config is reformatted.
func replaceKey(t *testing.T, body, key, value string) string {
	t.Helper()
	re := regexp.MustCompile(`(?m)^` + regexp.QuoteMeta(key) + `\s*=.*$`)
	// Literal: prices contain '$', which ReplaceAllString would read as a
	// capture-group reference.
	out := re.ReplaceAllLiteralString(body, key+" = "+value)
	if out == body {
		t.Fatalf("replaceKey: %q not found in body", key)
	}
	return out
}

