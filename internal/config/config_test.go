// TestPerRailFacilitator covers the per-rail facilitator override: the same
// URL hardening as the global key, credentials arriving via headers + env, and
// the all-or-nothing inheritance rule (a rail with its own facilitator must
// not inherit the global credential — that would aim one facilitator's key at
// another facilitator's host).
func TestPerRailFacilitator(t *testing.T) {
	const good = "0x000000000000000000000000000000000000dEaD"
	base := func(railExtra, paymentsExtra string) string {
		return "upstream = \"127.0.0.1:3000\"\n[payments]\npay_to=\"" + good +
			"\"\nfacilitator=\"https://global.example\"\n" + paymentsExtra +
			"[[payments.rails]]\nnetwork=\"eip155:1\"\nasset=\"0xa\"\n" +
			"asset_name=\"T\"\nasset_version=\"1\"\n" + railExtra +
			"[[payments.rules]]\nname=\"s\"\npaths=[\"/*\"]\nprice=\"$1\"\npaid_ttl=\"1h\"\n"
	}
	load := func(t *testing.T, body string) (*Config, error) {
		t.Helper()
		path := filepath.Join(t.TempDir(), "anteroom.toml")
		if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
		return Load(path)
	}

	t.Run("inherits URL and headers as a unit", func(t *testing.T) {
		t.Setenv("TEST_FAC_KEY", "sekrit")
		cfg, err := load(t, base("", "facilitator_headers=[\"Authorization: Bearer ${TEST_FAC_KEY}\"]\n"))
		if err != nil {
			t.Fatal(err)
		}
		rl := cfg.Payments.Rails[0]
		if rl.Facilitator != "https://global.example" {
			t.Errorf("facilitator = %q, want the global", rl.Facilitator)
		}
		if got := rl.FacilitatorHeader.Get("Authorization"); got != "Bearer sekrit" {
			t.Errorf("Authorization = %q, want the expanded global header", got)
		}
	})

	t.Run("own facilitator does not inherit global headers", func(t *testing.T) {
		cfg, err := load(t, base("facilitator=\"https://own.example\"\n",
			"facilitator_headers=[\"Authorization: Bearer globalkey\"]\n"))
		if err != nil {
			t.Fatal(err)
		}
		rl := cfg.Payments.Rails[0]
		if rl.Facilitator != "https://own.example" {
			t.Errorf("facilitator = %q", rl.Facilitator)
		}
		if got := rl.FacilitatorHeader.Get("Authorization"); got != "" {
			t.Errorf("a rail with its own facilitator inherited the global credential: %q", got)
		}
	})

	t.Run("own headers expand and parse", func(t *testing.T) {
		t.Setenv("TEST_RAIL_KEY", "abc123")
		cfg, err := load(t, base("facilitator=\"https://own.example\"\n"+
			"facilitator_headers=[\"Authorization: Bearer ${TEST_RAIL_KEY}\"]\n", ""))
		if err != nil {
			t.Fatal(err)
		}
		if got := cfg.Payments.Rails[0].FacilitatorHeader.Get("Authorization"); got != "Bearer abc123" {
			t.Errorf("Authorization = %q", got)
		}
	})

	rejects := []struct {
		name      string
		railExtra string
		payExtra  string
		wantErr   string
	}{
		{"per-rail plaintext non-loopback", "facilitator=\"http://f.example\"\n", "", "plaintext http"},
		{"per-rail non-http scheme", "facilitator=\"unix:/tmp/f\"\n", "", "not an http(s) URL"},
		{"userinfo in per-rail URL", "facilitator=\"https://user:key@f.example\"\n", "", "credentials in the URL"},
		{"userinfo in global URL is caught too", "", "", ""}, // handled below
		{"headers without facilitator", "facilitator_headers=[\"Authorization: Bearer k\"]\n", "", "without facilitator"},
		{"header missing colon", "facilitator=\"https://f.example\"\nfacilitator_headers=[\"NoColonHere\"]\n", "", "Name: value"},
		{"header empty name", "facilitator=\"https://f.example\"\nfacilitator_headers=[\": v\"]\n", "", "Name: value"},
		{"reserved header rejected case-insensitively", "facilitator=\"https://f.example\"\nfacilitator_headers=[\"content-type: x\"]\n", "", "owned by the gate"},
		{"invalid header name", "facilitator=\"https://f.example\"\nfacilitator_headers=[\"Bad Name: x\"]\n", "", "not a valid HTTP header name"},
		{"unset env var named in error", "facilitator=\"https://f.example\"\nfacilitator_headers=[\"Authorization: Bearer ${TEST_DEFINITELY_UNSET_VAR}\"]\n", "", "TEST_DEFINITELY_UNSET_VAR"},
	}
	for _, tt := range rejects {
		if tt.name == "userinfo in global URL is caught too" {
			continue
		}
		t.Run(tt.name, func(t *testing.T) {
			_, err := load(t, base(tt.railExtra, tt.payExtra))
			if err == nil {
				t.Fatalf("accepted %s", tt.name)
			}
			if !strings.Contains(err.Error(), tt.wantErr) {
				t.Errorf("error %q does not mention %q", err, tt.wantErr)
			}
		})
	}

	t.Run("per-rail loopback may be plaintext", func(t *testing.T) {
		if _, err := load(t, base("facilitator=\"http://127.0.0.1:9\"\n", "")); err != nil {
			t.Fatalf("rejected loopback plaintext per-rail facilitator: %v", err)
		}
	})

	t.Run("userinfo in the global URL", func(t *testing.T) {
		body := "upstream = \"127.0.0.1:3000\"\n[payments]\npay_to=\"" + good +
			"\"\nfacilitator=\"https://user:key@f.example\"\n" +
			"[[payments.rails]]\nnetwork=\"eip155:1\"\nasset=\"0xa\"\n" +
			"asset_name=\"T\"\nasset_version=\"1\"\n" +
			"[[payments.rules]]\nname=\"s\"\npaths=[\"/*\"]\nprice=\"$1\"\n"
		_, err := load(t, body)
		if err == nil || !strings.Contains(err.Error(), "credentials in the URL") {
			t.Errorf("global userinfo not rejected: %v", err)
		}
	})
}

// TestPayToAndFacilitatorHardening covers two config checks that exist because
// getting them wrong is silent and expensive.
func TestPayToAndFacilitatorHardening(t *testing.T) {
	const rails = "[[payments.rails]]\nnetwork=\"eip155:1\"\nasset=\"0xa\"\n" +
		"asset_name=\"T\"\nasset_version=\"1\"\n" +
		"[[payments.rules]]\nname=\"s\"\npaths=[\"/*\"]\nprice=\"$1\"\npaid_ttl=\"1h\"\n"
	const good = "0x000000000000000000000000000000000000dEaD"

	tests := []struct {
		name    string
		payTo   string
		facil   string
		wantErr string
	}{
		{"valid", good, "https://f.example", ""},
		{
			// A typo here advertises a recipient nobody controls, and every
			// payment made against the offer is lost. Nothing fails loudly at
			// runtime, so the config is the only place to catch it.
			name: "pay_to is not an address", payTo: "0xnope", facil: "https://f.example",
			wantErr: "not an EVM address",
		},
		{
			// Settlement verdicts decide whether content is served, so a forged
			// response over an unencrypted link is free access to paid content.
			name: "plaintext facilitator", payTo: good, facil: "http://f.example",
			wantErr: "plaintext http",
		},
		{"loopback may be plaintext", good, "http://127.0.0.1:8080", ""},
		{"localhost may be plaintext", good, "http://localhost:8080", ""},
		// The near misses, which are the rows that make the two above mean
		// something. Without them, loosening isLoopbackHost to a suffix or
		// prefix match — the natural "be helpful about hostnames" edit — passes
		// every accepting row, and an attacker-controlled host then qualifies as
		// loopback and gets to answer settlement verdicts over plaintext.
		{"a host that merely ends in localhost is not loopback", good,
			"http://localhost.attacker.example:8080", "plaintext http"},
		{"a host that merely starts with localhost is not loopback", good,
			"http://localhosts.example:8080", "plaintext http"},
		{"a public address in the 127 text is not loopback", good,
			"http://127.0.0.1.attacker.example:8080", "plaintext http"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			body := "upstream = \"127.0.0.1:3000\"\n[payments]\npay_to=\"" + tt.payTo +
				"\"\nfacilitator=\"" + tt.facil + "\"\n" + rails
			path := filepath.Join(t.TempDir(), "anteroom.toml")
			if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
				t.Fatal(err)
			}
			_, err := Load(path)
			if tt.wantErr == "" {
				if err != nil {
					t.Fatalf("rejected a valid config: %v", err)
				}
				return
			}
			if err == nil {
				t.Fatalf("accepted %s", tt.name)
			}
			if !strings.Contains(err.Error(), tt.wantErr) {
				t.Errorf("error %q does not mention %q", err, tt.wantErr)
			}
		})
	}
}
