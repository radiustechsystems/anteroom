// write writes a config file into a temp dir and returns its path.
func write(t *testing.T, body string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "anteroom.toml")
	if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	return p
}

const minimal = `upstream = "127.0.0.1:3000"` + "\n"

const paymentsHeader = `
[payments]
pay_to      = "0x000000000000000000000000000000000000dEaD"
facilitator = "https://facilitator.example"

[[payments.rails]]
network       = "eip155:72344"
asset         = "0xtoken"
asset_name    = "Stable Coin"
asset_version = "1"
asset_transfer_method = "permit2"
`

func TestLoadMinimal(t *testing.T) {
	cfg, err := Load(write(t, minimal))
	if err != nil {
		t.Fatalf("Load: %v", err)
	}
	// Defaults hold.
	// ":8080" and not ":80": the default must bind as an ordinary user.
	if cfg.Listen != ":8080" || cfg.PassTTL.D() != 60*time.Second || cfg.MaxSession.D() != 30*time.Minute || cfg.ShutdownGrace.D() != 5*time.Second {
		t.Errorf("time defaults wrong: %+v", cfg)
	}
	if cfg.Difficulty != 14 || cfg.RenewDifficulty != 6 {
		t.Errorf("difficulty defaults wrong: %+v", cfg)
	}
	if !cfg.Inject || !cfg.Triage.JSONAccept {
		t.Error("inject/json_accept should default true")
	}
	// No admin listener unless asked for: it is unauthenticated, so silently
	// opening a port the operator never configured would be a surprise surface.
	if cfg.AdminListen != "" {
		t.Errorf("admin_listen should default off, got %q", cfg.AdminListen)
	}
	// A key was generated and flagged.
	if len(cfg.HMACKeys) != 1 || !cfg.KeyAutoGenerated {
		t.Errorf("auto key: %+v, flag %v", cfg.HMACKeys, cfg.KeyAutoGenerated)
	}
	keys, err := cfg.Keys()
	if err != nil || len(keys) != 1 || len(keys[0].Key) != 32 {
		t.Errorf("Keys() = %v, %v", keys, err)
	}
	u, err := cfg.UpstreamURL()
	if err != nil || u.String() != "http://127.0.0.1:3000" {
		t.Errorf("UpstreamURL = %v, %v", u, err)
	}
}

func TestLoadFullPayments(t *testing.T) {
	cfg, err := Load(write(t, minimal+paymentsHeader+`
[[payments.rules]]
name  = "site"
paths = ["/*"]
price = "$0.01"
paid_ttl = "1h"

[[payments.rules]]
name  = "reports"
paths = ["/reports/*"]
price = "2.50"
paid_ttl = "24h"
`))
	if err != nil {
		t.Fatalf("Load: %v", err)
	}
	r := cfg.Payments.Rules
	const rail0 = "eip155:72344"
	if r[0].PriceAtomic[rail0].String() != "10000" { // $0.01 at 6 decimals
		t.Errorf("site price atomic = %s, want 10000", r[0].PriceAtomic[rail0])
	}
	if r[1].PriceAtomic[rail0].String() != "2500000" {
		t.Errorf("reports price atomic = %s, want 2500000", r[1].PriceAtomic[rail0])
	}
	rail := cfg.Payments.Rails[0]
	if rail.Decimals != 6 {
		t.Errorf("decimals default = %d", rail.Decimals)
	}
	if rail.AssetName != "Stable Coin" || rail.AssetVersion != "1" {
		t.Errorf("EIP-712 domain not loaded: %q/%q", rail.AssetName, rail.AssetVersion)
	}
	// pay_to falls through to the rail unless overridden.
	if rail.PayTo != "0x000000000000000000000000000000000000dEaD" {
		t.Errorf("rail pay_to = %q, want the payments-level address", rail.PayTo)
	}
	// maxTimeoutSeconds is a required wire field, so it needs a usable default.
	if cfg.Payments.MaxTimeoutSeconds != 300 {
		t.Errorf("max_timeout_seconds default = %d, want 300", cfg.Payments.MaxTimeoutSeconds)
	}
}

