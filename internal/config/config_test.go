// TestUpstreamSocket pins the unix-socket forms. Application servers bound to a
// socket rather than a port are ordinary — gunicorn, puma, uwsgi and php-fpm
// all default that way in common packaging — and the alternative to supporting
// them is asking an operator to reconfigure someone else's service to
// accommodate the gate.
func TestUpstreamSocket(t *testing.T) {
	tests := []struct {
		upstream string
		want     string
	}{
		{"unix:/run/app.sock", "/run/app.sock"},
		{"unix:///run/app.sock", "/run/app.sock"},
		{"unix:/var/run/php/php8.4-fpm.sock", "/var/run/php/php8.4-fpm.sock"},

		// Not sockets: these must keep their existing meaning exactly.
		{"127.0.0.1:3000", ""},
		{"http://127.0.0.1:3000", ""},
		{"https://app.internal", ""},
		{"app:3000", ""},

		// Malformed: a relative path is not a socket we will dial, and must not
		// be silently treated as one.
		{"unix:relative/path.sock", ""},
		{"unix:", ""},
		{"unix://", ""},
	}
	for _, tt := range tests {
		t.Run(tt.upstream, func(t *testing.T) {
			c := &Config{Upstream: tt.upstream}
			if got := c.UpstreamSocket(); got != tt.want {
				t.Errorf("UpstreamSocket(%q) = %q, want %q", tt.upstream, got, tt.want)
			}
		})
	}
}

// TestUpstreamURLWithSocket checks that a socket upstream still yields a usable
