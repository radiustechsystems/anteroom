// TestMultipleRails: offering more than one way to pay is what makes a gate
// payable by a wallet that only holds funds on one chain — the client filters
// accepts[] to what it registered and pays the first survivor.
func TestMultipleRails(t *testing.T) {
	cfg, err := Load(write(t, minimal+`
[payments]
pay_to      = "0x000000000000000000000000000000000000dEaD"
facilitator = "https://f.example"

[[payments.rails]]
network       = "eip155:72344"
asset         = "0xsbc"
asset_name    = "Stable Coin"
asset_version = "1"
asset_transfer_method = "permit2"

[[payments.rails]]
network       = "eip155:8453"
asset         = "0xusdc"
decimals      = 6
asset_name    = "USD Coin"
asset_version = "2"
pay_to        = "0x000000000000000000000000000000000000BEEF"

[[payments.rules]]
name  = "site"
paths = ["/*"]
price = "$0.01"
paid_ttl = "1h"
`))
	if err != nil {
		t.Fatalf("Load: %v", err)
	}
	if len(cfg.Payments.Rails) != 2 {
		t.Fatalf("rails = %d, want 2", len(cfg.Payments.Rails))
	}
	// The same display price resolves once per rail.
	pa := cfg.Payments.Rules[0].PriceAtomic
	if pa["eip155:72344"].String() != "10000" || pa["eip155:8453"].String() != "10000" {
		t.Errorf("per-rail prices wrong: %v", pa)
	}
	// The second rail's transfer method defaults and its pay_to override wins.
	if cfg.Payments.Rails[1].AssetTransferMethod != "eip3009" {
		t.Errorf("rail 2 transfer method = %q", cfg.Payments.Rails[1].AssetTransferMethod)
	}
	if cfg.Payments.Rails[1].PayTo != "0x000000000000000000000000000000000000BEEF" {
		t.Errorf("rail 2 pay_to override ignored: %q", cfg.Payments.Rails[1].PayTo)
	}
}

